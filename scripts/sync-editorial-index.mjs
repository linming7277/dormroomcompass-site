// Synchronizes src/data/editorialIndex.ts from the markdown content sources.
//
// The markdown files under src/content/ are the authoritative editorial
// content; card components and data utilities still need *synchronous* access
// to guide/review metadata (they call getProductReview() /
// getProductReadingPath() inside .map() render loops and cannot await
// getCollection()). This script therefore generates a metadata-only index
// (frontmatter, never bodies) from the .md sources.
//
// Zero dependencies: node:fs + JSON.parse. Frontmatter is JSON syntax, so
// parsing is identical to the Python contract validator. Output is
// deterministic (stable key order) so a regenerated index in a release copy
// matches the accepted snapshot byte-for-byte.

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const contentDir = path.join(root, "src/content");

function readFrontmatter(file) {
  const text = fs.readFileSync(file, "utf8");
  const match = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) {
    throw new Error(`no frontmatter in ${file}`);
  }
  let value;
  try {
    value = JSON.parse(match[1]);
  } catch (error) {
    throw new Error(`invalid JSON frontmatter in ${file}: ${error.message}`);
  }
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`frontmatter is not an object in ${file}`);
  }
  return value;
}

function listCollection(name) {
  const dir = path.join(contentDir, name);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => readFrontmatter(path.join(dir, f)));
}

const guides = listCollection("guides");
const reviews = listCollection("reviews");

const output =
  "// GENERATED by scripts/sync-editorial-index.mjs. Do not edit.\n" +
  `export const editorialGuides = ${JSON.stringify(guides, null, 2)};\n` +
  `export const editorialReviews = ${JSON.stringify(reviews, null, 2)};\n`;

const outPath = path.join(root, "src/data/editorialIndex.ts");
fs.writeFileSync(outPath, output);
console.log(
  `sync-editorial-index: ${guides.length} guides, ${reviews.length} reviews -> ${path.relative(root, outPath)}`,
);
